export type FighterId = 'kazemaru' | 'hotaru' | 'raidenbo' | 'yuki';

export type StageId = 'crimson_torii' | 'indigo_bamboo' | 'golden_temple' | 'snow_shrine';

export interface AttackFrameData {
  name: string;
  kanji: string;
  startup: number;      // frames before active hitbox
  active: number;       // frames hitbox is live
  recovery: number;     // frames after active before idle
  damage: number;
  chipDamage: number;
  meterGain: number;
  hitstun: number;
  blockstun: number;
  knockbackX: number;
  knockbackY: number;
  reachX: number;
  reachY: number;
  offsetY: number;
  slashArcStart: number;
  slashArcEnd: number;
  slashRadius: number;
  isHeavy?: boolean;
  isSpecial?: boolean;
  isSuper?: boolean;
  spawnsProjectile?: boolean;
  forwardImpulse?: number;
  upwardImpulse?: number;
}

export interface FighterConfig {
  id: FighterId;
  name: string;
  kanji: string;
  title: string;
  description: string;
  portraitUrl: string;
  maxHealth: number;
  walkSpeed: number;
  dashSpeed: number;
  jumpForce: number;
  bodyWidth: number;
  bodyHeight: number;
  // Japanese watercolor & ink palette
  primaryInk: string;
  robeColor: string;
  accentWatercolor: string;
  secondaryWatercolor: string;
  bladeGlow: string;
  weaponType: 'katana' | 'twin_kodachi' | 'kanabo_nodachi' | 'frost_naginata';
  hatType: 'sedge_ronin' | 'kitsune_mask' | 'monk_mane' | 'snow_hairpins';
  statsLabel: { speed: string; power: string; reach: string };
  attacks: Record<
    'light' | 'medium' | 'heavy' | 'special1' | 'special2' | 'super',
    AttackFrameData
  >;
}

